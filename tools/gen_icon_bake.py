"""Makes src/iconbake_data.inc: the pictures that the screens ask icon_render() for the first time they are drawn, ready-made.

    python3 tools/gen_icon_bake.py

Calculating them took 0.3 to 1 second on a PSP when the Media tab or Settings came into view (the three pictures of the Music, Videos and
Images cards alone are some 11 ms on a PC at 16 samples a pixel, and a PSP is some 30 to 40 times slower), so they are stored (icons.c,
baked_render). The numbers below are exactly what the screens ask for (they were read from a run of the real screens with every icon_render
call logged: host-tests/perf/wrap_icons.c); a picture is only used for exactly those numbers, any other is calculated as before. The
images come from the same code, so they are what it would calculate; the host test host-tests/icons/iconbake_test.py checks that the file is up to
date. Run this again whenever one of these pictures changes. Needs gcc.

Each image is stored as pairs (coverage, run length) in the order of the pixels, row by row.
"""
import ctypes as C
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")

# (kind, w, h, r, cx, cy, tw, th, what) with the floats as they are in the program (hexadecimal, so that nothing is rounded)
PICTURES = [
    ("ICON_MUSIC",   "0x0p+0", "0x0p+0", "0x1.48p+4",     "0x1.58p+4", "0x1.58p+4", 43, 43, "the Music card of the Media tab (gfx.c card_icon_image)"),
    ("ICON_VIDEO",   "0x0p+0", "0x0p+0", "0x1.7fc28ep+4", "0x1.9p+4",  "0x1.9p+4",  50, 50, "the Videos card"),
    ("ICON_IMAGES",  "0x0p+0", "0x0p+0", "0x1.6f5c2ap+4", "0x1.8p+4",  "0x1.8p+4",  48, 48, "the Images card"),
    ("ICON_CUBE",    "0x0p+0", "0x0p+0", "0x1p+3",        "0x1.4p+3",  "0x1.4p+3",  20, 20, "the cube of Settings (gfx_cube)"),
    ("ICON_NOTE",    "0x0p+0", "0x0p+0", "0x1.ep+3",      "0x1.1p+4",  "0x1.1p+4",  34, 34, "the note of the sound button"),
    ("ICON_SPEAKER", "0x0p+0", "0x0p+0", "0x1.ep+1",      "0x1.8p+2",  "0x1.4p+3",  12, 20, "the speaker"),
    ("ICON_BOLT",    "0x0p+0", "0x0p+0", "0x1.8p+2",      "0x1p+3",    "0x1p+3",    16, 16, "the charging bolt"),
    ("ICON_WIFI",    "0x0p+0", "0x0p+0", "0x1.cp+2",      "0x1.2p+3",  "0x1.2p+3",  18, 18, "the Wi-Fi sign of the top bar"),
    ("ICON_GEAR",    "0x0p+0", "0x0p+0", "0x1.cp+2",      "0x1.2p+3",  "0x1.2p+3",  18, 18, "the cog of the top bar"),
    ("ICON_FOLDER",  "0x1.3p+4", "0x1.cp+3", "0x0p+0",    "0x1.3p+3",  "0x1.cp+2",  19, 14, "the folder of the File Manager's list"),
    ("ICON_RRECT",   "0x1.cp+2", "0x1.cp+2", "0x1p+1",    "0x1.2p+2",  "0x1.2p+2",   9,  9, "a small rounded square"),
    ("ICON_RRECT",   "0x1.cp+2", "0x1.cp+2", "0x1.8p+0",  "0x1.2p+2",  "0x1.2p+2",   9,  9, "a small rounded square, a smaller corner"),
]


def kind_numbers():
    with open(os.path.join(SRC, "icons.h")) as f:
        return re.findall(r"\b(ICON_[A-Z_]+)\b\s*[,/\n]", f.read().split("enum {", 1)[1].split("};", 1)[0])


def build_lib(tmp):
    lib = os.path.join(tmp, "libicons.so")
    subprocess.check_call(["gcc", "-O2", "-shared", "-fPIC", "-DICON_NO_BAKED", "-I" + SRC, "-o", lib, os.path.join(SRC, "icons.c"), "-lm"])
    L = C.CDLL(lib)
    L.icon_render.argtypes = [C.c_int] + [C.c_float] * 5 + [C.c_int, C.c_int, C.c_void_p]
    return L


def render(L, names, spec):
    kind, w, h, r, cx, cy, tw, th, _ = spec
    out = (C.c_ubyte * (tw * th))()
    L.icon_render(names.index(kind), float.fromhex(w), float.fromhex(h), float.fromhex(r), float.fromhex(cx), float.fromhex(cy), tw, th, out)
    return bytes(out)


def rle(img):
    pairs, i = [], 0
    while i < len(img):
        j = i
        while j < len(img) and img[j] == img[i] and j - i < 255:
            j += 1
        pairs += [img[i], j - i]
        i = j
    return pairs


def make():
    names = kind_numbers()
    with tempfile.TemporaryDirectory() as tmp:
        L = build_lib(tmp)
        data, starts = [], []
        for spec in PICTURES:
            starts.append(len(data))
            data += rle(render(L, names, spec))
    out = ["/* Generated by tools/gen_icon_bake.py - do not edit. The pictures that icon_render() is asked for the first time a screen is drawn (icons.c, baked_render),",
           " * run length coded: pairs (coverage, number of pixels), row after row. */",
           "#define ICON_BAKED_COUNT %d" % len(PICTURES),
           "static const IconBake icon_baked[%d] = {" % len(PICTURES)]
    for spec, start in zip(PICTURES, starts):
        kind, w, h, r, cx, cy, tw, th, what = spec
        out.append("    { %d, %d, %d, %s, %s, %s, %s, %s, %d }, /* %s: %s %dx%d */" % (names.index(kind), tw, th, fl(w), fl(h), fl(r), fl(cx), fl(cy), start, kind, what, tw, th))
    out.append("};")
    out.append("static const unsigned char icon_baked_data[%d] = {" % len(data))
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(v) for v in data[i:i + 24]) + ",")
    out.append("};")
    return "\n".join(out) + "\n"


def fl(h):
    """a C float constant that is exactly the hexadecimal value (it is a float: the f)"""
    return "%sf" % float.fromhex(h).hex()


if __name__ == "__main__":
    text = make()
    path = os.path.join(SRC, "iconbake_data.inc")
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        with open(path) as f:
            sys.exit(0 if f.read() == text else 1)
    with open(path, "w") as f:
        f.write(text)
    print("wrote", path, len(text), "bytes")
